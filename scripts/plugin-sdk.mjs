// Writes public/sdk/*.js: the modules installed plugins import at run time ('@buildtrack/sdk',
// 'react', 'react/jsx-runtime', mapped by the import maps in index.html and sandbox.html). Each
// re-exports what the app put on globalThis.__buildtrack (src/plugins/loader.tsx and
// src/sandbox/main.tsx), so plugins use the app's own React and kit.
//
//   node scripts/plugin-sdk.mjs          write them
//   node scripts/plugin-sdk.mjs --check  fail if they're out of date (npm run check)
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { createRequire } from 'node:module';

const root = new URL('..', import.meta.url).pathname;
const require = createRequire(import.meta.url);
const kitSrc = readFileSync(`${root}src/plugins/kit.tsx`, 'utf8');
const block = kitSrc.match(/export const kit = \{([\s\S]*?)\n\};/);
if (!block) throw new Error('Could not find `export const kit = { … }` in src/plugins/kit.tsx');
const kitNames = [...block[1].matchAll(/^\s{2}([A-Za-z_$][\w$]*)\s*[,:]/gm)].map((m) => m[1]);
const reactNames = Object.keys(require('react')).filter((k) => !k.startsWith('__') && k !== 'default' && /^[A-Za-z_$][\w$]*$/.test(k));
const jsxNames = Object.keys(require('react/jsx-runtime'));

const head = (what) => `// Generated by scripts/plugin-sdk.mjs: ${what}. Don't edit.\n`;
const mod = (src, names, what) =>
  `${head(what)}const m = globalThis.__buildtrack.${src};\nexport default m;\n${names.map((n) => `export const ${n} = m.${n};`).join('\n')}\n`;

const files = {
  // for type checking plugins (tsconfig paths '@buildtrack/sdk'); esbuild leaves the import as is
  'src/plugins/sdk-module.ts': `${head("what plugins import from '@buildtrack/sdk', for type checking")}import { kit } from './kit';\nexport default kit;\nexport const {\n${kitNames.map((n) => `  ${n},`).join('\n')}\n} = kit;\n`,
  'public/sdk/buildtrack.js': mod('kit', kitNames, "the BuildTrack plugin kit ('@buildtrack/sdk', src/plugins/kit.tsx)"),
  'public/sdk/react.js': mod('React', reactNames, "the app's React, for plugins"),
  'public/sdk/react-jsx-runtime.js': mod('jsxRuntime', jsxNames, "the app's JSX runtime, for plugins"),
};

const check = process.argv.includes('--check');
let stale = [];
for (const [path, text] of Object.entries(files)) {
  const full = root + path;
  if (check) {
    if (!existsSync(full) || readFileSync(full, 'utf8') !== text) stale.push(path);
  } else {
    mkdirSync(full.replace(/\/[^/]+$/, ''), { recursive: true });
    writeFileSync(full, text);
  }
}
if (stale.length) {
  console.error(`Out of date: ${stale.join(', ')}. Run: node scripts/plugin-sdk.mjs`);
  process.exit(1);
}
console.log(check ? 'Plugin SDK modules are up to date.' : `Wrote public/sdk (${kitNames.length} kit exports).`);
